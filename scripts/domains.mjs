/** The spell of a domain ("fire"; "fire-apocryphal" → nothing): a compendium uuid, or null. */
export function domainSpell(domain, advanced = false) {
  const id = DOMAIN_SPELLS[String(domain ?? "")]?.[advanced ? 1 : 0];
  return id ? `Compendium.pf2e.spells-srd.Item.${id}` : null;
}

/** The domain of a domain spell, by its id (a translation's mirror keeps the ids). */
export function domainOfSpell(uuid) {
  const id = String(uuid ?? "").split(".").pop();
  return Object.keys(DOMAIN_SPELLS).find(d => DOMAIN_SPELLS[d].includes(id)) ?? null;
}
